// Turns seed/paris.json into seed/seed.sql, to load the starting places once.
// After that, the database is the source of truth: edit places from the site, not here.
//
//   node scripts/seed-to-sql.mjs [seed/paris.json] [seed/seed.sql]
//
// Uses "insert or ignore" so running it twice never overwrites edits made on the site.

import { readFileSync, writeFileSync } from 'node:fs';
import { parseHours } from '../src/lib/hours.js';

const [input = 'seed/paris.json', output = 'seed/seed.sql'] = process.argv.slice(2);
const data = JSON.parse(readFileSync(input, 'utf8'));

export function sql(value) {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'number') return String(value);
  if (typeof value === 'boolean') return value ? '1' : '0';
  return `'${String(value).replace(/'/g, "''")}'`;
}

const lines = ['-- Generated by scripts/seed-to-sql.mjs. Do not edit by hand.', ''];
const c = data.city;
lines.push(
  `insert or ignore into cities (id, name, lat, lng, zoom) values (${[c.id, c.name, c.lat, c.lng, c.zoom].map(sql).join(', ')});`,
);

for (const l of data.layers) {
  lines.push(
    `insert or ignore into layers (id, city_id, name, color, shape, icon, sort, visible_by_default) values (${[l.id, c.id, l.name, l.color, l.shape, l.icon, l.sort, l.visible_by_default ?? true].map(sql).join(', ')});`,
  );
}

const layerIds = new Set(data.layers.map((l) => l.id));
const seen = new Set();
for (const p of data.places) {
  if (!layerIds.has(p.layer)) throw new Error(`${p.id}: unknown layer ${p.layer}`);
  if (seen.has(p.id)) throw new Error(`duplicate place ${p.id}`);
  seen.add(p.id);
  const cols = {
    id: p.id,
    layer_id: p.layer,
    name: p.name,
    summary: p.summary ?? '',
    tip: p.tip ?? '',
    address: p.address ?? '',
    lat: p.lat,
    lng: p.lng,
    path: p.path ? JSON.stringify(p.path) : null,
    website: p.website ?? null,
    booking_required: Boolean(p.booking_required),
    price: p.price ?? '',
    hours_note: p.hours_note ?? '',
    wikidata_id: p.wikidata ?? null,
    favourite: Boolean(p.favourite),
    category: p.category ?? null,
    duration: p.duration ?? null,
    best_time: p.best_time ?? null,
    area: p.area ?? null,
  };
  lines.push(
    `insert or ignore into places (${Object.keys(cols).join(', ')}) values (${Object.values(cols).map(sql).join(', ')});`,
  );
  for (const h of parseHours(p.hours)) {
    lines.push(
      `insert or ignore into opening_hours (place_id, weekday, opens, closes) values (${[p.id, h.weekday, h.opens, h.closes].map(sql).join(', ')});`,
    );
  }
  if (p.photo) {
    const credit = data.photos[p.photo];
    if (!credit) throw new Error(`${p.id}: no credit for photo ${p.photo}`);
    const page = `https://commons.wikimedia.org/wiki/File:${encodeURIComponent(p.photo.replace(/ /g, '_'))}`;
    lines.push(
      `insert or ignore into photos (id, place_id, source, file, author, license, source_url) values (${[`${p.id}-1`, p.id, 'commons', p.photo, credit[0], credit[1], page].map(sql).join(', ')});`,
    );
  }
}

for (const e of data.events ?? []) {
  lines.push(
    `insert or ignore into events (id, place_id, title, kind, category, starts_on, ends_on, date_note, url, summary) values (${[e.id, e.place ?? null, e.title, e.kind, e.category ?? null, e.starts_on ?? null, e.ends_on ?? null, e.date_note ?? '', e.url ?? null, e.summary ?? ''].map(sql).join(', ')});`,
  );
}

for (const z of data.areas ?? []) {
  lines.push(
    `insert or ignore into areas (id, city_id, name, summary, duration, best_time, cover_place_id, route, sort) values (${[z.id, c.id, z.name, z.summary, z.duration, z.best_time, z.cover, JSON.stringify(z.route), z.sort ?? 0].map(sql).join(', ')});`,
  );
}

// Adventures belong to the first user: create your account (scripts/create-user.mjs) before seeding.
for (const a of data.adventures ?? []) {
  lines.push(
    `insert or ignore into adventures (id, owner_id, city_id, title, subtitle, starts_on, ends_on, party_size, guests, language, palette) ` +
      `select ${[a.id].map(sql)}, id, ${[c.id, a.title, a.subtitle, a.starts_on, a.ends_on, a.party_size, JSON.stringify(a.guests), a.language, a.palette].map(sql).join(', ')} ` +
      `from users order by created_at limit 1;`,
  );
}

writeFileSync(output, lines.join('\n') + '\n');
console.log(`${output}: ${data.places.length} places, ${data.layers.length} layers`);
